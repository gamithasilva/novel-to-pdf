package com.ak.novel2pdf.service;

import com.lowagie.text.Document;
import com.lowagie.text.Font;
import com.lowagie.text.Paragraph;
import com.lowagie.text.PageSize;
import com.lowagie.text.pdf.PdfWriter;
import org.springframework.stereotype.Service;

import java.io.ByteArrayOutputStream;
import java.util.List;

@Service
public class PdfService {

    public byte[] generateMultiChapterPdf(
            String novelTitle,
            List<NovelService.ChapterData> chapters
    ) {

        try {

            ByteArrayOutputStream outputStream =
                    new ByteArrayOutputStream();

            Document document =
                    new Document(
                            PageSize.A4,
                            50,
                            50,
                            50,
                            50
                    );

            PdfWriter.getInstance(
                    document,
                    outputStream
            );

            document.open();

            // ==========================================
            // FONTS
            // ==========================================

            Font novelTitleFont =
                    new Font(
                            Font.HELVETICA,
                            24,
                            Font.BOLD
                    );

            Font tocTitleFont =
                    new Font(
                            Font.HELVETICA,
                            18,
                            Font.BOLD
                    );

            Font chapterTitleFont =
                    new Font(
                            Font.HELVETICA,
                            18,
                            Font.BOLD
                    );

            Font contentFont =
                    new Font(
                            Font.HELVETICA,
                            11,
                            Font.NORMAL
                    );

            // ==========================================
            // TITLE PAGE
            // ==========================================

            Paragraph title =
                    new Paragraph(
                            novelTitle,
                            novelTitleFont
                    );

            title.setAlignment(
                    Paragraph.ALIGN_CENTER
            );

            document.add(title);

            document.add(
                    new Paragraph("\n\n\n")
            );

            Paragraph generated =
                    new Paragraph(
                            "Generated by Novel2PDF"
                    );

            generated.setAlignment(
                    Paragraph.ALIGN_CENTER
            );

            document.add(generated);

            // ==========================================
            // TABLE OF CONTENTS
            // ==========================================

            document.newPage();

            Paragraph tocTitle =
                    new Paragraph(
                            "Table of Contents",
                            tocTitleFont
                    );

            tocTitle.setAlignment(
                    Paragraph.ALIGN_CENTER
            );

            document.add(tocTitle);

            document.add(
                    new Paragraph("\n")
            );

            int chapterNumber = 1;

            for (NovelService.ChapterData chapter : chapters) {

                Paragraph tocEntry =
                        new Paragraph(
                                chapterNumber +
                                        ". " +
                                        chapter.title()
                        );

                tocEntry.setSpacingAfter(8);

                document.add(tocEntry);

                chapterNumber++;
            }

            // ==========================================
            // CHAPTERS
            // ==========================================

            chapterNumber = 1;

            for (NovelService.ChapterData chapter : chapters) {

                document.newPage();

                // Chapter heading
                Paragraph chapterHeading =
                        new Paragraph(
                                chapter.title(),
                                chapterTitleFont
                        );

                chapterHeading.setAlignment(
                        Paragraph.ALIGN_CENTER
                );

                document.add(chapterHeading);

                document.add(
                        new Paragraph("\n")
                );

                // Chapter content
                String[] paragraphs =
                        chapter.content()
                                .split("\\n\\n");

                for (String text : paragraphs) {

                    text = text.trim();

                    if (!text.isEmpty()) {

                        Paragraph paragraph =
                                new Paragraph(
                                        text,
                                        contentFont
                                );

                        paragraph.setSpacingAfter(10);

                        document.add(paragraph);
                    }
                }

                chapterNumber++;
            }

            document.close();

            return outputStream.toByteArray();

        } catch (Exception e) {

            throw new RuntimeException(
                    "Failed to generate multi-chapter PDF",
                    e
            );
        }
    }
}